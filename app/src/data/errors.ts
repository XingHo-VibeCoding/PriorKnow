// 数据层的错误类型 —— 别处的 catch 靠它做分类
//
// 为什么单独一个文件、而且必须放在 data/ 而不是 ui/：
//
//   仓储实现（local-indexeddb.ts）在动库之前会先校验入参，校验不过就抛错。
//   这个错**是数据层抛的**，而判断「这属于输入问题还是别的什么」是界面层的事。
//   如果把这个类写进 ui/，数据层就得反过来 import 界面层 ——
//   层级就倒了（本项目从 Day 17 起坚持「入口 → 业务 → 数据」单向依赖）。
//
// 所以：**类型住在抛它的那一层，解释住在读它的那一层。**
//
// 为什么不直接 `throw new Error('任务内容不能为空')` 就算了：
//   那样界面层只能靠「文案里有没有中文」去猜这是哪一类错误。
//   猜文案是会错的 —— 比如「任务不存在」也是中文，但它要用户做的是刷新，
//   不是改输入。给一个类名，判断就有确定性，不用猜。

/**
 * 入参不合法。**改了就能过**，不需要重试、不需要看网络。
 *
 * 凡是「用户填的东西不合规」，都用它，包括：
 *   · 标题为空
 *   · 预计耗时是负数 / 不是数字
 *   · 导入的 JSON 里某一条缺字段或类型不对
 */
export class ValidationError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'ValidationError'
  }
}
