-- =============================================================================
-- 🔴 为什么 due_at 用 now() + interval 而不是写死日期
--
-- 写死的话（'2026-10-13 09:00'），过几天再跑seed 就会出现：
--   sample-01/02/03 全变成「已逾期」
--   sample-06「下个月交」永远不变
--   → 7 条数据再也无法展示算法的六种分支，示例废了。
--
-- 现在这样写，任何时候跑都是：
--   1 条逾期 + 1 条 9 小时内 + 1 条 30 小时内 + 1 条 5 天后
--   + 1 条 30 天后（紧迫度 0）+ 2 条无期限
--
-- ⚠️ 与前端对齐：app/src/data/sampleTasks.ts:68 是
--     createdAt: new Date(base - (SAMPLE_SPECS.length - index) * MINUTE_MS)
--   7 条 →偏移 7/6/5/4/3/2/1 分钟（**不是** 6/5/4/3/2/1/0）。
--   本脚本的 7 个值已与之逐条对齐。
--   ⚠️ 注意：前端那行用的是**数组下标 index**，而本文件的插入顺序
--   与SAMPLE_SPECS 一致，两者才对应得上 —— 改顺序时必须同步改偏移值。
-- =============================================================================


