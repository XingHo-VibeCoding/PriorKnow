-- -----------------------------------------------------------------------------
-- 第 1 步：清空
--
-- 为什么是 TRUNCATE 而不是 DELETE：
--   DELETE 只删数据、不重置序列，重复执行会让 seq 一路涨到几千；
--   TRUNCATE ... RESTART IDENTITY 顺带把 seq 序列归零，
--   所以重复执行后seq 永远是 1–7 —— 截图永远长得一样。
--
--⚠️ TRUNCATE 会清空 tasks 表**全部**数据，不分分区。
--   这是刻意的：seed 之后库里就该是「干净的 7 条示例」，
--   否则你手动插的测试行（u-test / t-test）会混在截图里。
--   Day 17 起库里有了真实数据后，🔴 不要再执行本脚本。
--
--⚠️ TRUNCATE 要求表上不能有外键引用它 —— 本项目只有一张表，不存在这个问题。
-- -----------------------------------------------------------------------------
TRUNCATE TABLE tasks RESTART IDENTITY;


