/**
 * 面向用户的固定文案 —— 一处定义，多处引用。
 *
 * 为什么值得单独一个文件，而不是在每处直接写字符串：
 *
 *   同一个处境（服务器自己出错）在三处地方会被说出来：
 *     ① GET 的 catch（tasks/handlers.js）
 *     ② 三个写入口共用的 applyChanges 的 catch（tasks/handlers.js）
 *     ③ 入口层最后一道网（index.js）
 *   三处各写一遍，最先变形的一定是它们 —— 改了一处忘了另一处，
 *   用户就会看到「服务器内部错误」「服务端出错了」两种说法描述同一件事。
 *   Day 23 整天的主题就是**统一**，这里也不能例外。
 *
 * 为什么放在根目录而不是 tasks/ 或 http/ 里：
 *   业务层（tasks/）和入口层（index.js）都要用它。放进 tasks/
 *   就成了「入口层反过来依赖业务层」，放进 http/ 则是业务层依赖入口层，
 *   两个方向都把单向依赖拆了。放在这一层（谁都能往下拿，它自己谁也不依赖）才对。
 */

/**
 * 服务端内部出错的唯一说法。
 *
 * 🔴 改这句话时守住三条：
 *   ① **不透露内部细节** —— 不写异常类型、表名、SQL、连接串。
 *      这些对用户没用，对攻击者有用。
 *   ② **不带「怎么办」** —— 「稍后再试」已经够了，但**不要**在这里写
 *      「不是你填错了」这类安抚。那句安抚由前端在展示时补
 *      （见 app/src/ui/errors.ts 的 5xx 分支），因为它还知道 HTTP 状态码、
 *      还能加上标签。服务端只负责说「发生了什么」。
 *   ③ 两个地方各说各的，才不会有「服务器内部错误，请稍后再试 ——
 *      不是你填错了，稍等一会儿重试」这种一句话里劝两遍的文案。
 */
